-- BugTrack — single source of truth for the relational schema.
-- Executed by Spring Boot at startup (spring.sql.init.schema-locations).
-- JPA runs with ddl-auto: validate, so the entity mapping must match this file exactly.

CREATE TABLE IF NOT EXISTS issues (
    id          BIGSERIAL PRIMARY KEY,
    title       VARCHAR(200) NOT NULL,
    description TEXT NOT NULL CHECK (length(description) BETWEEN 1 AND 5000),
    severity    VARCHAR(8)   NOT NULL CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    priority    VARCHAR(8)   NOT NULL CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'URGENT')),
    status      VARCHAR(12)  NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'IN_PROGRESS', 'CLOSED')),
    -- Timestamps are generated by the backend in UTC; the DB defaults are a safety net only.
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
