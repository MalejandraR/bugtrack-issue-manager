-- BugTrack — single source of truth for the relational schema.
-- Executed by Spring Boot at startup (spring.sql.init.schema-locations).
-- JPA runs with ddl-auto: validate, so the entity mapping must match this file exactly.

CREATE TABLE IF NOT EXISTS issues (
    id          BIGSERIAL PRIMARY KEY,
    title       VARCHAR(200) NOT NULL,
    description TEXT NOT NULL CHECK (length(description) BETWEEN 1 AND 5000),
    severity    VARCHAR(8)   NOT NULL CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    priority    VARCHAR(8)   NOT NULL CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'URGENT')),
    status      VARCHAR(12)  NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'IN_PROGRESS', 'CLOSED')),
    -- Timestamps are generated by the backend in UTC; the DB defaults are a safety net only.
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Application users (Fase 7). Registration is closed: rows are created only by the
-- startup seed (AdminUserSeeder from AUTH_ADMIN_* env vars) — there is no public
-- register endpoint. password_hash holds a BCrypt hash (60 chars), never a password.
CREATE TABLE IF NOT EXISTS users (
    id            BIGSERIAL PRIMARY KEY,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Uniqueness on lower(email): logins are matched case-insensitively, so Admin@x
-- and admin@x must be the same account. A plain UNIQUE (email) would not stop that.
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_email ON users (lower(email));
